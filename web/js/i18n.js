// Idioma del chrome (mismos criterios que applyI18n): 2 letras, ES por defecto.
export function uiLang() {
  return (navigator.language || 'es').slice(0, 2).toLowerCase();
}

// Traduce un string de runtime del chrome con sustitución {var}. Fallback:
// idioma → inglés → la propia clave. La elfa ya responde en el idioma del
// navegador; esto localiza los textos que pinta la UI (pensando, modelo listo,
// el «¡Listo!» del payoff, los resultados de app.*).
export function t(key, vars) {
  const s = (L[uiLang()] || L.en)[key] ?? L.en[key] ?? key;
  return vars ? s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? '')) : s;
}

const CHIP_ACCIONES = [null, null, 'carpeta', null, null, null];

// Una sugerencia (chip) tal cual, en cualquiera de los idiomas → la misma en
// español, o null si no es una. El modo Básico (providers/rules.js) entiende
// órdenes en español: en inglés, francés o alemán casi todos los chips caían en
// su texto de ayuda en vez de hacer lo que dicen.
export function chipEnEspanol(texto) {
  const x = String(texto ?? '').trim().toLowerCase();
  if (!x) return null;
  for (const idioma of Object.values(L)) {
    const i = (idioma.chips || []).findIndex(c => c.trim().toLowerCase() === x);
    if (i >= 0) return L.es.chips[i];
  }
  return null;
}

export function applyI18n() {
  const code = uiLang();
  const t = L[code] || L.en;
  const $ = s => document.querySelector(s);
  const set = (sel, txt) => { const e = $(sel); if (e && txt) e.textContent = txt; };

  document.documentElement.lang = code;
  const sys = $('.msg.sys');
  if (sys) {
    // Reconstruir el saludo entero: el welcome del HTML mezcla nodos de texto
    // con un <i>se crean</i>, así que limpiar solo los text-nodes dejaba ese
    // fragmento español y salía «Привіт, I'm Elffuss.se crean An operating…».
    // replaceChildren() vacía TODO; conservamos el avatar y ponemos <b>hi</b> welcome.
    const avatar = sys.querySelector('.avatar');
    sys.replaceChildren();
    if (avatar) sys.append(avatar);
    const b = document.createElement('b');
    b.textContent = t.hi;
    sys.append(b, ' ' + t.welcome);
  }
  // Los chips salen del idioma, enteros (antes se sobrescribían por posición y
  // sobraban o faltaban). La acción va por posición: la 3.ª abre el selector.
  const chips = $('#chips');
  if (chips && Array.isArray(t.chips)) {
    chips.replaceChildren(...t.chips.map((txt, i) => {
      const b = document.createElement('button');
      b.type = 'button'; b.className = 'chip'; b.textContent = txt;
      if (CHIP_ACCIONES[i]) b.dataset.accion = CHIP_ACCIONES[i];
      return b;
    }));
    chips.setAttribute('aria-label', t.chipsL || L.en.chipsL);
  }
  document.querySelectorAll('#tabs button').forEach(b => { const k = b.dataset.tab; if (t.tabs[k]) b.textContent = t.tabs[k]; });
  $('#tabs')?.setAttribute('aria-label', t.tabsLabel || L.en.tabsLabel);
  const ph = $('#prompt'); if (ph) ph.placeholder = t.ph;
  set('#btn-perms', t.perms);
  set('.brand .claim:not(#build)', t.claim || L.en.claim);   // el lema de la cabecera (se quedaba en español)
  // Botones de solo icono: su nombre accesible, en el idioma de la página (antes
  // era el title en español en todos los idiomas).
  const nombre = (sel, key) => { const e = $(sel); const v = t[key] || L.en[key]; if (e && v) { e.title = v; e.setAttribute('aria-label', v); } };
  nombre('#btn-clear', 'newChat');
  $('#prompt')?.setAttribute('aria-label', t.promptL || L.en.promptL);   // la caja tenía por nombre solo el placeholder
  set('#vista-empty p', t.empty); // simplifica: solo la 1ª línea
  const emptyP = $('#vista-empty p'); if (emptyP) emptyP.innerHTML = `${t.empty}<br><i>${t.tryit}</i>`;
  set('#splash .l1', t.s1); set('#splash .l2', t.s2); set('#splash .l3', t.s3);
  const s4 = $('#splash .l4'); if (s4) s4.textContent = t.s4 + ' 😉';
  set('#splash-enter', t.enter + ' ✳'.replace(' ✳', ''));
  set('#splash-enter', t.enter);
  const h1 = $('#splash h1'); if (h1) h1.innerHTML = t.hi.replace('Elffuss', '<b>Elffuss Claw</b>');
  set('#perm-deny', t.permDeny);
  set('#perm-allow', t.permAllow);
}
